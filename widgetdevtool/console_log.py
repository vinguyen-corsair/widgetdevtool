"""Console capture: JavaScript console output, uncaught errors and bridge notices."""
from __future__ import annotations

from dataclasses import dataclass

from PySide6.QtCore import QObject, Signal
from PySide6.QtWebEngineCore import QWebEnginePage

_LEVELS = {
    QWebEnginePage.JavaScriptConsoleMessageLevel.InfoMessageLevel: "info",
    QWebEnginePage.JavaScriptConsoleMessageLevel.WarningMessageLevel: "warning",
    QWebEnginePage.JavaScriptConsoleMessageLevel.ErrorMessageLevel: "error",
}

BRIDGE_SOURCE = "bridge"  # entries generated by the dev tool itself, not by the widget


@dataclass(frozen=True)
class ConsoleEntry:
    level: str  # "info" | "warning" | "error"
    message: str
    line: int = 0
    source: str = ""

    def format(self) -> str:
        where = self.source if self.source == BRIDGE_SOURCE else f"{self.source}:{self.line}"
        return f"[{self.level}] {self.message}  ({where})"


class ConsoleLog(QObject):
    added = Signal(object)  # ConsoleEntry

    def __init__(self, parent: QObject | None = None) -> None:
        super().__init__(parent)
        self.entries: list[ConsoleEntry] = []

    def add(self, level: str, message: str, line: int = 0, source: str = BRIDGE_SOURCE) -> None:
        entry = ConsoleEntry(level, message, line, source)
        self.entries.append(entry)
        self.added.emit(entry)

    def notice(self, message: str, level: str = "warning") -> None:
        self.add(level, message, 0, BRIDGE_SOURCE)

    def clear(self) -> None:
        self.entries.clear()

    def matching(self, level: str | None = None, contains: str | None = None, widget_only: bool = False):
        return [
            e for e in self.entries
            if (level is None or e.level == level)
            and (contains is None or contains in e.message)
            and not (widget_only and e.source == BRIDGE_SOURCE)
        ]


class ConsolePage(QWebEnginePage):
    """QWebEnginePage that forwards console messages (incl. uncaught errors) to a ConsoleLog."""

    def __init__(self, profile, log: ConsoleLog, parent: QObject | None = None) -> None:
        super().__init__(profile, parent)
        self._log = log

    def javaScriptConsoleMessage(self, level, message, lineNumber, sourceID):  # noqa: N802 (Qt naming)
        self._log.add(_LEVELS.get(level, "info"), message, lineNumber, sourceID)